export interface IndustryAgentDef {
  code: string;
  name: string;
  sector: string;
  excerpt: string; // 一句话卖点
  painPoints: string[]; // 该行业 AI 应用的"道之痛"
  injectionPoints: string[]; // 道的注入点
  promptPack: string; // 行业注入提示词包
  sampleQuestions: string[]; // 演示问题
  pricing: string; // 落地模式示意
  unlockCost: number; // 积分解锁价（FR-P02）
  custom?: boolean; // 是否为用户自定义生成
  ownerUserId?: string; // 生成者（本人免费解锁）
  anchorChapters?: number[]; // 道系锚点章节（检索为空时的经文兜底）
}

